#!/usr/bin/env bash
# Regenerate e2e/identity-keys.ts: throwaway public keys for the
# identity-binding specs (identity-binding.spec.ts) -- a contact, a
# DIFFERENT key wearing that contact's exact user ID, a same-name key
# under another address, a Cyrillic look-alike name, and an innocent
# bystander. Public halves only; the secrets die with the temp homedir.
# Run from apps/pgp:
#   ./e2e/gen-identity-keys.sh
# Requires gpg (2.4+) and python3.
set -euo pipefail
cd "$(dirname "$0")/.."

export GNUPGHOME="$(mktemp -d)"
trap 'rm -rf "$GNUPGHOME"' EXIT

python3 - << 'PYEOF'
import json, subprocess

MSG = "Identity binding: this note is signed by Alice."

def gpg(*args, input=None):
    return subprocess.run(
        ["gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "", *args],
        input=input, capture_output=True, text=True, check=True,
    ).stdout

def gen(uid):
    """Generate a fresh ed25519/cv25519 key (no expiry) and return its fpr.
    Fingerprints are read back by listing, newest last, because several
    keys share one user ID and a uid lookup would be ambiguous."""
    before = set(fprs())
    # --yes: gpg refuses a second key with an existing user ID otherwise,
    # and a second key with an existing user ID is the whole point.
    gpg("--yes", "--quick-generate-key", uid, "default", "default", "never")
    (new,) = set(fprs()) - before
    return new

def fprs():
    out = gpg("--list-keys", "--with-colons")
    res, take = [], False
    for line in out.splitlines():
        f = line.split(":")
        if f[0] == "pub":
            take = True
        elif f[0] == "fpr" and take:
            res.append(f[9]); take = False
    return res

def export(fpr, *opts):
    return gpg("--armor", *opts, "--export", fpr)

# The Cyrillic capital A (U+0410) is built with chr() so no escape sequence
# ever passes through a shell.
CYRILLIC_ALICE = chr(0x410) + "lice"

alice = gen("Alice <alice@example.test>")
alice_public = export(alice)
# The same cert re-exported minimal: an "already saved" copy riding along
# in a bundle, as a pasted keyring dump would carry it.
alice_minimal = export(alice, "--export-options", "export-minimal")
alice_signed = gpg("--clearsign", "-u", alice, input=MSG)
# A genuine update of Alice's own key: a new encryption subkey. Re-importing
# it is the same fingerprint, so a "verified" mark must survive it.
gpg("--quick-add-key", alice, "cv25519", "encr", "never")
alice_updated = export(alice)

impostor = gen("Alice <alice@example.test>")
other_email = gen("Alice <alice@other.test>")
lookalike = gen(CYRILLIC_ALICE + " <alice@lookalike.test>")
bob = gen("Bob Bystander <bob@example.test>")

rows = [
    ("alice", "Alice <alice@example.test>", alice, alice_public,
     "the contact: Alice, as first saved", alice_signed),
    ("aliceMinimal", "Alice <alice@example.test>", alice, alice_minimal,
     "Alice's own key re-exported minimal (a duplicate of `alice`)", None),
    ("aliceUpdated", "Alice <alice@example.test>", alice, alice_updated,
     "Alice's own key with an extra encryption subkey (an update)", None),
    ("impostor", "Alice <alice@example.test>", impostor, export(impostor),
     "a DIFFERENT key with Alice's exact user ID", None),
    ("otherEmail", "Alice <alice@other.test>", other_email, export(other_email),
     "same name as Alice, different address", None),
    ("lookalike", CYRILLIC_ALICE + " <alice@lookalike.test>", lookalike,
     export(lookalike), "Alice's name with a Cyrillic capital A, other address", None),
    ("bob", "Bob Bystander <bob@example.test>", bob, export(bob),
     "an unrelated new key", None),
]

L = [
    "// AUTO-GENERATED by e2e/gen-identity-keys.sh -- do not edit by hand.",
    "// Throwaway PUBLIC keys for identity-binding.spec.ts: a contact, a",
    "// different key wearing her exact user ID, same-name and look-alike",
    "// keys under other addresses, and a bystander. No secrets are kept.",
    "",
    "export interface IdentityKey {",
    "  slug: string;",
    "  description: string;",
    "  /** The cert's (only) user ID. Non-ASCII is written escaped. */",
    "  uid: string;",
    "  fingerprint: string;",
    "  publicKey: string;",
    "  /** Cleartext-signed copy of SIGNED_MESSAGE (alice only). */",
    "  signedMessage?: string;",
    "}",
    "",
    f"export const SIGNED_MESSAGE = {json.dumps(MSG)};",
    "",
    "export const IDENTITY_KEYS = {",
]
for slug, uid, fpr, pub, desc, signed in rows:
    L.append(f"  {slug}: {{")
    L.append(f"    slug: {json.dumps(slug)},")
    L.append(f"    description: {json.dumps(desc)},")
    # json.dumps escapes non-ASCII as \uXXXX: the file stays ASCII.
    L.append(f"    uid: {json.dumps(uid)},")
    L.append(f"    fingerprint: {json.dumps(fpr)},")
    L.append(f"    publicKey: {json.dumps(pub)},")
    if signed:
        L.append(f"    signedMessage: {json.dumps(signed)},")
    L.append("  },")
L += ["} satisfies Record<string, IdentityKey>;", ""]
open("e2e/identity-keys.ts", "w").write("\n".join(L))
print("wrote e2e/identity-keys.ts with", len(rows), "keys")
PYEOF
