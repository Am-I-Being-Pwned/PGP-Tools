#!/usr/bin/env bash
# Regenerate e2e/message-trust.ts: "PGP MESSAGE" blocks that were never
# encrypted, and a text-mode signature over a lone CR. Public material
# only -- the signer's secret key lives in a throwaway GNUPGHOME and is
# gone when this exits.
# Run from apps/pgp:
#   ./e2e/gen-message-trust.sh
# Requires gpg (2.4+) and python3.
set -euo pipefail
cd "$(dirname "$0")/.."

export GNUPGHOME="$(mktemp -d)"
trap 'rm -rf "$GNUPGHOME"' EXIT

G(){ gpg --batch --pinentry-mode loopback --passphrase '' "$@"; }

G --quick-generate-key "Sam Signer <sam@signer.example>" ed25519 sign never >/dev/null 2>&1
FPR=$(gpg --list-keys --with-colons sam@signer.example | awk -F: '/^fpr:/{print $10;exit}')

python3 - "$FPR" << 'PYEOF'
import base64, json, subprocess, sys

fpr = sys.argv[1]

def gpg(*args, inp=None):
    r = subprocess.run(["gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
                        *args], capture_output=True, input=inp, check=True)
    return r.stdout

PUBLIC = "Sam's public statement: the release is signed and ready."
# Uncompressed, so the literal packet can be found and rewritten below.
signed_armored = gpg("--armor", "--compress-algo", "none", "--sign", "-u", fpr, inp=PUBLIC.encode())
signed_binary = gpg("--compress-algo", "none", "--sign", "-u", fpr, inp=PUBLIC.encode())
stored = gpg("--armor", "--compress-algo", "none", "--store", inp=b"Plain text, only encoded.")
text_signed = gpg("--compress-algo", "none", "--textmode", "--sign", "-u", fpr, inp=b"Approved:\nNO")

def packets(data):
    """(tag, body) for each packet. gpg mixes old-format (OPS, signature)
    and new-format (literal) headers, all with one-octet lengths for
    packets this small."""
    out, i = [], 0
    while i < len(data):
        ctb = data[i]
        if ctb & 0xC0 == 0xC0:
            tag = ctb & 0x3F
        else:
            assert ctb & 0x83 == 0x80, "old format, one-octet length only"
            tag = (ctb >> 2) & 0x0F
        n = data[i + 1]
        assert n < 192, "one-octet length only"
        out.append((tag, data[i + 2:i + 2 + n]))
        i += 2 + n
    return out

def literal_with(body, data):
    # format, filename length, filename, 4-byte date, then the data.
    flen = body[1]
    return body[:2 + flen + 4] + data

def crc24(data):
    crc = 0xB704CE
    for b in data:
        crc ^= b << 16
        for _ in range(8):
            crc <<= 1
            if crc & 0x1000000:
                crc ^= 0x1864CFB
    return crc & 0xFFFFFF

def armor(data):
    b64 = base64.b64encode(data).decode()
    lines = [b64[i:i + 64] for i in range(0, len(b64), 64)]
    crc = base64.b64encode(crc24(data).to_bytes(3, "big")).decode()
    return "-----BEGIN PGP MESSAGE-----\n\n" + "\n".join(lines) + f"\n={crc}\n-----END PGP MESSAGE-----\n"

# The same signature, with the signed "Approved:\r\nNO" (gpg's textmode
# stores CRLF) swapped for "Approved:\rNO". Sequoia's text-mode hashing
# reads both as one line break. Re-emitted with new-format headers.
rebuilt = b""
for tag, body in packets(text_signed):
    if tag == 11:
        body = literal_with(body, b"Approved:\rNO")
    rebuilt += bytes([0xC0 | tag, len(body)]) + body
lone_cr = armor(rebuilt)

r = subprocess.run(["gpg", "--batch", "--verify"], input=lone_cr.encode(), capture_output=True)
gpg_lone_cr = "good" if r.returncode == 0 else "bad"

fixture = {
    "fingerprint": fpr,
    "publicKey": gpg("--armor", "--export", fpr).decode(),
    "publicStatement": PUBLIC,
    "signedOnly": signed_armored.decode(),
    "signedOnlyBinaryB64": base64.b64encode(signed_binary).decode(),
    "storedOnly": stored.decode(),
    "loneCr": lone_cr,
}

with open("e2e/message-trust.ts", "w") as f:
    f.write("// AUTO-GENERATED by e2e/gen-message-trust.sh -- do not edit by hand.\n")
    f.write("// \"PGP MESSAGE\" blocks with no encryption layer, and a text-mode\n")
    f.write("// signature re-pointed at a lone CR. Public material only.\n")
    f.write(f"// GnuPG's own verdict on the lone-CR copy when generated: {gpg_lone_cr}.\n\n")
    f.write("export const SAM = " + json.dumps(fixture, indent=2) + " as const;\n")
print(f"wrote e2e/message-trust.ts (gpg on lone CR: {gpg_lone_cr})")
PYEOF
