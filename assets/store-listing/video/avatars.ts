/**
 * Writes avatars.js: KeyAvatar faces drawn by the extension's own
 * lib/key-avatar, so every face in the video is one the app would draw.
 * The first is Alice (the `standard` e2e fixture, the recipient in the
 * captures); the rest come from throwaway fingerprints derived from a
 * counter, which belong to no key at all.
 *
 *     npx tsx assets/store-listing/video/avatars.ts
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";

import { keyAvatar } from "../../../apps/pgp/lib/key-avatar";

const ALICE = "1D2DFAC2C18051E9C11037A6E3AA99801E250E69";
const prints = [ALICE];
for (let i = 0; prints.length < 72; i++)
  prints.push(
    createHash("sha1").update(`pgp-tools-video-${i}`).digest("hex").toUpperCase(),
  );

// Per face: a small palette plus 256 indices, to keep the file small.
const faces = prints.map((fp) => {
  const { cells } = keyAvatar(fp);
  const palette: string[] = [];
  const idx = cells.map((c) => {
    let k = palette.indexOf(c);
    if (k < 0) k = palette.push(c) - 1;
    return k;
  });
  return { p: palette, c: idx.map((n) => n.toString(36)).join("") };
});

writeFileSync(
  path.join(import.meta.dirname, "avatars.js"),
  `// Generated by avatars.ts. Do not edit.\nwindow.AVATARS = ${JSON.stringify(faces)};\n`,
);
console.log("wrote", faces.length, "faces");
